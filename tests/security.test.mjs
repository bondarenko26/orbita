import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,rmSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir=mkdtempSync(path.join(os.tmpdir(),'orbita-test-'));
const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,DATA_DIR:dir,PORT:'0'},stdio:['ignore','pipe','pipe']});
let out='';const ready=new Promise((resolve,reject)=>{child.stdout.on('data',d=>{out+=d;const m=out.match(/Орбита: http:\/\/127.0.0.1:(\d+)/);if(m)resolve({url:'http://127.0.0.1:'+m[1],accounts:JSON.parse(out.slice(out.indexOf('[\n'),out.lastIndexOf(']')+1))})});child.on('error',reject);child.on('exit',c=>{if(c)reject(Error('Server exited '+c))})});
after(async()=>{child.kill();await new Promise(r=>child.once('exit',r));rmSync(dir,{recursive:true,force:true})});
test('real sessions, ownership, roles, persistence and club workflow',async()=>{
 const {url,accounts}=await ready;
 async function req(p,b,cookie){const r=await fetch(url+'/api/'+p,{method:b===undefined?'GET':'POST',headers:{...(b===undefined?{}:{'Content-Type':'application/json'}),...(cookie?{cookie}:{})},body:b===undefined?undefined:JSON.stringify(b)});return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]}}
 const login=async name=>{const a=accounts.find(a=>a.login===name);return req('login',{login:a.login,password:a.password})};
 assert.equal((await req('me')).status,401);
 assert.equal((await req('login',{login:'student1',password:'incorrect'})).status,401);
 const a=await login('student1'),b=await login('student2'),s=await login('staff'),coach=await login('coach'),admin=await login('admin');
 assert.equal(a.status,200);assert.equal(a.body.password,undefined);
 assert.equal((await req('manage',undefined,a.cookie)).status,403);
 const sa=await req('schedule?date=2026-11-09',undefined,a.cookie),sb=await req('schedule?date=2026-11-09',undefined,b.cookie);
 assert.equal(sa.body.lessons.length,3);assert.notEqual(sa.body.lessons[0].grp,sb.body.lessons[0].grp);
 assert.equal((await req('notes',{lesson_id:sb.body.lessons[0].id,date:'2026-11-09',text:'foreign'},a.cookie)).status,404);
 await req('notes',{lesson_id:sa.body.lessons[0].id,date:'2026-11-09',text:'Private note'},a.cookie);
 assert.equal((await req('schedule?date=2026-11-09',undefined,a.cookie)).body.lessons[0].note,'Private note');
 const r=await req('requests',{type:'Справка об обучении',comment:'test'},a.cookie);assert.equal(r.status,201);
 assert.equal((await req('requests/'+r.body.id,undefined,b.cookie)).status,404);
 assert.equal((await req('requests',undefined,b.cookie)).body.length,0);
 assert.equal((await req('manage/requests',{id:r.body.id,status:'Готова'},a.cookie)).status,403);
 assert.equal((await req('manage/requests',{id:r.body.id,status:'Готова',reply:'Можно получить'},s.cookie)).status,200);
 assert.equal((await req('requests/'+r.body.id,undefined,a.cookie)).body.status,'Готова');
 await req('join',{club_id:1},a.cookie);const m=(await req('manage',undefined,coach.cookie)).body.memberships[0];
 await req('manage/memberships',{id:m.id,status:'Вы приняты'},coach.cookie);
 assert.equal((await req('schedule?date=2026-11-10',undefined,a.cookie)).body.clubs.length,1);
 await req('theme',{theme:'light'},a.cookie);assert.equal((await req('me',undefined,a.cookie)).body.theme,'light');
 const newUser={login:'newstudent',password:'Strong-Demo-2026!',name:'Новый Тестовый',role:'student',faculty:'Тест',program:'Тест',course:1,grp:'ИС-201'};
 assert.equal((await req('manage/users',newUser,admin.cookie)).status,201);
 const n=await req('login',{login:newUser.login,password:newUser.password});assert.equal(n.status,200);
 assert.equal((await req('requests',undefined,n.cookie)).body.length,0);
 const csrf=await fetch(url+'/api/theme',{method:'POST',headers:{cookie:a.cookie,'Content-Type':'application/json',Origin:'https://evil.example'},body:JSON.stringify({theme:'dark'})});assert.equal(csrf.status,403);
 await req('logout',{},a.cookie);assert.equal((await req('me',undefined,a.cookie)).status,401);
});
